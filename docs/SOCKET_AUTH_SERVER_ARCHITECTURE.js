/**
 * ═══════════════════════════════════════════════════════════════════════════════
 * 9. TIMELINE OF A SUCCESSFUL SESSION
 * ═══════════════════════════════════════════════════════════════════════════════
 *
 * USER LOGS IN:
 *   POST /auth/login { email, password }
 *     ↓
 *   Server generates JWT:
 *     access: expires in 15min
 *     refresh: expires in 7 days (stored in httpOnly cookie)
 *     Returns: { user, message: 'Login successful' }
 *   ↓
 *   Client stores: localStorage['accessToken'] = JWT
 *
 * SOCKET CONNECTION:
 *   const socket = io(url, {
 *     auth: { 
 *       token: getAccessToken(),         // From localStorage
 *       deviceId: getDeviceFingerprint() // From sessionStorage
 *     }
 *   })
 *     ↓
 *   Server receives handshake
 *     ↓
 *   io.use(authenticateSocket):
 *     - Extract token from auth
 *     - jwt.verify(token) ✓
 *     - Extract claims: userId, sessionId, deviceId
 *     - Verify device fingerprint matches ✓
 *     - Attach to socket.data
 *     ↓
 *   'connection' event fires ✓
 *   socket.emit('connect:success', { socketId, userId })
 *
 * JOIN ROOM:
 *   socket.emit('room:join', { roomId: 'room-123' })
 *     ↓
 *   socket.onAuth() wrapper runs:
 *     - Check socket.data.userId exists ✓
 *     - Check rate limit: 'user:123:room:join' ✓
 *     - Check room exists ✓
 *     - Execute handler
 *       - socket.join(roomId)
 *       - trackRoomJoin(socket, roomId)
 *       - Broadcast to room
 *       ✓
 *     ↓
 *   ack({ success: true, roomId })
 *
 * SEND CHAT:
 *   socket.emit('room:chat', { roomId: 'room-123', message: 'Hi!' })
 *     ↓
 *   socket.onAuth() wrapper:
 *     - Check socket.data.userId ✓
 *     - Check rate limit: 'user:123:room:chat' ✓
 *     - Check isUserInRoom(socket, 'room-123') ✓
 *     - Check input validation ✓
 *     - Execute handler
 *       - io.to(roomId).emit('room:activity', { type: 'chat', userId, message })
 *       ✓
 *     ↓
 *   ack({ success: true })
 *   Other users in room receive: 'room:activity' event
 *
 * TOKEN EXPIRING (after 10 minutes):
 *   Server interval detects:
 *     - socket.data.tokenExpiry - now <= 300 seconds
 *     - socket.emit('auth:expiring', { expiresIn: 300 })
 *       ↓
 *   Client receives 'auth:expiring'
 *       ↓
 *   Client calls: await POST /auth/refresh-token
 *       ↓
 *   Server generates new JWT + refresh token
 *       ↓
 *   Client updates: socket.auth.token = newToken
 *       ↓
 *   Client emits: socket.emit('socket:reauth', { token: newToken })
 *       ↓
 *   Server middleware verifies new token
 *   socket.data.tokenExpiry updated ✓
 *   socket.data._expiryWarned = false (reset warning flag)
 *       ↓
 *   ack({ success: true })
 *   Session continues seamlessly
 *
 * USER LOGS OUT:
 *   socket.emit('logout', {})
 *   OR
 *   User clicks logout button
 *     ↓
 *   Client clears: localStorage.removeItem('accessToken')
 *   Client calls: POST /auth/logout
 *   Server: User.findByIdAndUpdate(userId, { refreshToken: null })
 *   Client calls: socket.disconnect()
 *     ↓
 *   Server: 'disconnect' event
 *     - Clean up onlineUsers
 *     - Clean up roomsState
 *     - resetUserRateLimits(userId)
 *     ↓
 *   Redirect to /login
 */

