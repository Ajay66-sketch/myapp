// ──────────────────────────────────────────────────────────────────────────────
// SOCKET.IO JWT AUTHENTICATION - SERVER ARCHITECTURE GUIDE
// ──────────────────────────────────────────────────────────────────────────────
//
// This guide explains the production-grade Socket.IO authentication architecture
// implemented on the server side.
//
// Key Components:
// 1. authenticateSocket - Middleware that verifies JWT on connection
// 2. eventWrapper - Wraps event handlers with auth & rate limit checks
// 3. rateLimitStore - In-memory rate limiting store
// 4. permissionMiddleware - Validates room membership
// 5. socket.js - Refactored to use authenticated event handlers
//
// ──────────────────────────────────────────────────────────────────────────────

/**
 * ═══════════════════════════════════════════════════════════════════════════════
 * 1. AUTHENTICATION FLOW
 * ═══════════════════════════════════════════════════════════════════════════════
 *
 * CLIENT SIDE:
 *   io.connect(url, {
 *     auth: {
 *       token: 'JWT_TOKEN',      // From POST /auth/login
 *       deviceId: 'fingerprint'  // Device fingerprint
 *     }
 *   })
 *
 * SERVER SIDE (Handshake):
 *   1. io.use(authenticateSocket) middleware runs
 *   2. Extracts token from socket.handshake.auth.token
 *   3. jwt.verify(token, JWT_SECRET) - validates signature & expiry
 *   4. Extracts claims: userId, sessionId, deviceId, exp
 *   5. Validates device fingerprint matches token
 *   6. Attaches user data to socket.data:
 *      {
 *        userId: "507f1f77bcf86cd799439011",
 *        sessionId: "abc123xyz",
 *        deviceId: "device-fingerprint",
 *        tokenExpiry: 1234567890,
 *        connectedAt: Date.now(),
 *        ip: "192.168.1.1",
 *        userAgent: "Mozilla/5.0...",
 *        rooms: new Set(),
 *        lastActivity: Date.now()
 *      }
 *   7. If validation fails → error sent to client → connection rejected
 *   8. If success → 'connection' event fires with authenticated socket
 *
 * RECONNECTION:
 *   - Client gets 401 error on event → calls refreshToken()
 *   - Client updates token: socket.auth.token = newToken
 *   - Client calls socket.emit('socket:reauth', { token: newToken })
 *   - Socket middleware validates new token
 *   - All subsequent events use new token
 */

/**
 * ═══════════════════════════════════════════════════════════════════════════════
 * 2. JWT TOKEN CLAIMS
 * ═══════════════════════════════════════════════════════════════════════════════
 *
 * Generated by POST /auth/login:
 *
 * Access Token (15 minute TTL):
 * {
 *   sub: userId,                      // Subject - who token is for
 *   sessionId: sessionId,              // Session identifier
 *   deviceId: deviceFingerprint,       // Device fingerprint
 *   iss: 'myapp',                      // Issuer
 *   iat: 1234567890,                   // Issued at
 *   exp: 1234571490,                   // Expires at
 *   type: 'access',                    // Token type
 *   scope: 'user:read,socket:connect'  // Permissions
 * }
 *
 * Client should not decode token on client side (security risk)
 * Server extracts these claims during verification
 */

/**
 * ═══════════════════════════════════════════════════════════════════════════════
 * 3. EVENT HANDLER PATTERN
 * ═══════════════════════════════════════════════════════════════════════════════
 *
 * OLD (No Auth):
 *   socket.on('room:chat', ({ roomId, message }) => {
 *     // No verification!
 *     // Anyone could impersonate anyone
 *   })
 *
 * NEW (Authenticated):
 *   socket.onAuth('room:chat', function(data, ack) {
 *     // Automatically verified:
 *     // ✓ socket.data.userId exists (JWT verified)
 *     // ✓ Rate limit checked (max 10/sec per user)
 *     // ✓ User in room (socket.data.rooms.has(roomId))
 *     // ✓ Input validated
 *     
 *     const { roomId, message } = data;
 *     
 *     // Only business logic here
 *     io.to(roomId).emit('room:activity', {
 *       type: 'chat',
 *       userId: socket.data.userId,  // Verified user
 *       message
 *     });
 *     
 *     ack?.({ success: true });
 *   }, {
 *     requireRoom: true,  // Verify user in room
 *     roomIdParam: 'roomId'
 *   });
 *
 * What happens under the hood:
 *   1. Client emits event with data
 *   2. socket.onAuth() wrapper runs
 *   3. Checks socket.data exists (was authenticated on connect)
 *   4. Checks rate limit: checkRateLimit(userId, 'room:chat')
 *   5. If rate limited → ack({ error: { error: 'auth:rate_limited' } })
 *   6. Validates input data against schema (if validation provided)
 *   7. If requireRoom=true: validates isUserInRoom(socket, roomId)
 *   8. If all checks pass → calls handler function
 *   9. Updates activity tracking: socket.data.lastActivity = now
 */

/**
 * ═══════════════════════════════════════════════════════════════════════════════
 * 4. RATE LIMITING
 * ═══════════════════════════════════════════════════════════════════════════════
 *
 * In-memory rate limiting store with per-event limits
 *
 * Configuration (src/socket/constants.js):
 *   RATE_LIMITS = {
 *     TIMER_START: { limit: 3, windowMs: 5000 },      // 3 per 5 seconds
 *     ROOM_CHAT: { limit: 10, windowMs: 1000 },       // 10 per second
 *     ROOM_TYPING: { limit: 5, windowMs: 1000 },      // 5 per second
 *     ROOM_JOIN: { limit: 5, windowMs: 60000 },       // 5 per minute
 *   }
 *
 * How it works:
 *   1. Event arrives: socket.emit('room:chat', { message: '...' })
 *   2. Middleware calls: checkRateLimit(userId, 'room:chat')
 *   3. RateLimitStore checks key: 'user:123:room:chat'
 *   4. Returns: { allowed: true/false, remaining, resetIn }
 *   5. If not allowed: ack({ error: { error: 'auth:rate_limited', resetIn: 800 } })
 *   6. Client waits 800ms before retrying
 *
 * Memory management:
 *   - Entries auto-cleanup after window expires and count reaches 0
 *   - On disconnect: resetUserRateLimits(userId) clears all user entries
 *   - Prevents memory leaks
 *
 * Advantages:
 *   ✓ Low latency (memory only, no DB calls)
 *   ✓ Per-user limits (not per-socket, prevents reconnect abuse)
 *   ✓ Scalable (cleanup on disconnect)
 *   ✓ Tunable per event type
 *   ✓ Graceful degradation (tells client when to retry)
 */

/**
 * ═══════════════════════════════════════════════════════════════════════════════
 * 5. TOKEN EXPIRY HANDLING
 * ═══════════════════════════════════════════════════════════════════════════════
 *
 * Server monitors token expiry every 30 seconds:
 *
 *   setInterval(() => {
 *     io.sockets.sockets.forEach(socket => {
 *       const now = Math.floor(Date.now() / 1000);
 *       const timeUntilExpiry = socket.data.tokenExpiry - now;
 *       
 *       if (timeUntilExpiry <= 300 && !socket.data._expiryWarned) {
 *         socket.emit('auth:expiring', { expiresIn: timeUntilExpiry })
 *         socket.data._expiryWarned = true
 *       }
 *     })
 *   }, 30000)
 *
 * Timeline:
 *   T=0min:   Access token issued (expires in 15min)
 *   T=10min:  Server emits 'auth:expiring' (5min remaining)
 *   T=10min:  Client receives, calls POST /auth/refresh-token
 *   T=10min:  Server returns new access + refresh tokens
 *   T=10min:  Client updates socket.auth.token = newToken
 *   T=10min:  Client emits 'socket:reauth' with new token
 *   T=10min:  Socket middleware verifies new token, updates socket.data
 *   T=15min:  Original token would have expired (but client has new one)
 *
 * If client doesn't refresh:
 *   T=15min:  Token expires
 *   T=15min:  Next socket.emit() fails validation
 *   T=15min:  Server sends error: { error: 'auth:expired', action: 'refresh_and_reconnect' }
 *   T=15min:  Client receives error, attempts refresh + reconnect
 *   T=15min:  If refresh fails: redirect to login
 */

/**
 * ═══════════════════════════════════════════════════════════════════════════════
 * 6. ROOM MEMBERSHIP VALIDATION
 * ═══════════════════════════════════════════════════════════════════════════════
 *
 * Prevents events like chat/timer from being used without joining room first
 *
 * Socket data tracks rooms:
 *   socket.data.rooms = new Set()  // Rooms user is in
 *   socket.data.currentRoomId = null
 *
 * On room:join:
 *   1. Client emits: socket.emit('room:join', { roomId: '123' })
 *   2. Server validates room exists
 *   3. socket.join(roomId) - Socket.IO built-in room membership
 *   4. trackRoomJoin(socket, roomId) - Add to our tracking
 *   5. Broadcast to room: socket.to(roomId).emit('room:user_joined', ...)
 *
 * On room:chat:
 *   1. Client emits: socket.emit('room:chat', { roomId: '123', message: '...' })
 *   2. Middleware checks: isUserInRoom(socket, roomId)
 *   3. If not in room: ack({ error: { error: 'auth:permission_denied', reason: 'Not in room' } })
 *   4. If in room: proceed to handler
 *
 * On room:leave (implicit):
 *   1. When user joins different room: socket.leave(oldRoomId)
 *   2. When user disconnects: cleanup rooms
 *   3. trackRoomLeave(socket, roomId) - Remove from tracking
 *
 * Benefits:
 *   ✓ Prevents chat spam from non-room users
 *   ✓ Prevents timer manipulation from strangers
 *   ✓ Prevents impersonation (userId verified via JWT)
 *   ✓ Quick checks (memory-only, no DB queries)
 */

/**
 * ═══════════════════════════════════════════════════════════════════════════════
 * 7. ERROR RESPONSE CODES
 * ═══════════════════════════════════════════════════════════════════════════════
 *
 * Server sends structured error responses to client:
 *
 * {
 *   error: 'auth:expired',              // Error code (always starts with 'auth:')
 *   message: 'Token has expired',       // Human-readable message
 *   statusCode: 401,                    // HTTP equivalent status
 *   action: 'refresh_and_reconnect',    // What client should do
 *   recoverable: true,                  // Can be fixed by refresh
 *   expiresIn: 60,                      // (Optional) Seconds until expiry
 *   resetIn: 800,                       // (Optional) Rate limit reset time
 * }
 *
 * Client should handle different actions:
 *   - 'redirect_to_login': Clear auth, redirect to /login
 *   - 'refresh_and_reconnect': Refresh token, reconnect socket
 *   - 'refresh_token': Refresh token proactively
 *   - 'wait_and_retry': Rate limited, try again after delay
 *   - 'none': Error but no action needed
 */

